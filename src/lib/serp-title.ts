/**
 * (2026-11-15 · SEO) ضبط عنوان نتائج البحث (SERP) على السقف العملي — بلا اقتطاع.
 *
 * الخلفية المقيسة: 12 صفحة دليل كانت عناوينها بين 63 و65 حرفًا، والسبب في
 * كلها لاحقة العلامة التجارية « | اليسر ميديكال» (16 حرفًا) أو « | اليسر»
 * (8 أحرف) — أي أن النص التحريري نفسه داخل الحد، والزائد هو التوقيع. Google
 * يعرض ≈60 حرفًا ثم يقتطع بـ «…»، فيضيع آخر ما يراه الباحث.
 *
 * القاعدة هنا:
 *   1. العنوان داخل الحد → يُعاد كما هو (العلامة التجارية تبقى).
 *   2. العنوان يزيد **ولاحقته علامة تجارية** → تُحذف اللاحقة وحدها.
 *   3. العنوان يزيد بلا لاحقة → يُعاد كما هو ولا يُقتطع (القص قرار تحريري:
 *      الاقتطاع يقطع منتصف الكلمة ويجعل العناوين متشابهة). تدقيق
 *      `scripts/seo-audit.mjs` هو ما يمسك هذه الحالة ويطلب تعديل النص.
 *
 * لا تُكرِّر هذا المنطق في أي مكان آخر — استدعِ `fitSerpTitle`.
 */

/** السقف العملي لعرض العنوان كاملًا في نتائج سطح المكتب (‎≈580px). */
export const SERP_TITLE_MAX = 62;

/** أقل طول مقبول بعد حذف العلامة التجارية — أقل من ذلك يفقد العنوان معناه. */
const MIN_TITLE_AFTER_STRIP = 30;

/**
 * لاحقة العلامة التجارية كما تُكتب فعليًا في بيانات الموقع:
 * « | اليسر ميديكال» و« | اليسر» و« — اليسر ميديكال».
 */
const BRAND_SUFFIX = /\s*[|—–-]\s*اليسر(\s+ميديكال)?\s*$/u;

/**
 * يعيد العنوان بصيغة معروضة كاملة في SERP.
 *
 * @example
 * fitSerpTitle("كيف يؤثر التواصل بين الزوجين على الرغبة الجنسية | اليسر ميديكال")
 * // → "كيف يؤثر التواصل بين الزوجين على الرغبة الجنسية"
 */
export function fitSerpTitle(title: string, max: number = SERP_TITLE_MAX): string {
  const value = (title || "").trim();
  if ([...value].length <= max) return value;

  const withoutBrand = value.replace(BRAND_SUFFIX, "").trim();
  if (withoutBrand === value) return value; // لا لاحقة → لا تدخّل
  if ([...withoutBrand].length < MIN_TITLE_AFTER_STRIP) return value;
  if ([...withoutBrand].length > max) return value;

  return withoutBrand;
}
